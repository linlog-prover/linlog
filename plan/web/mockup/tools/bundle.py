# Bundles the text files under mockup-2/data/ into data.js, so that the page
# reads them from file:// (where fetch is blocked). Run after changing data/:
#   python3 tools/bundle.py
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = root / "data"
files = {}
for p in sorted(data.rglob("*")):
    if p.is_file() and p.suffix in {
        ".svg",
        ".json",
        ".txt",
        ".v",
        ".tex",
        ".typ",
        ".stderr",
    }:
        files[str(p.relative_to(data))] = p.read_text(encoding="utf-8")
out = (
    "// Generated by tools/bundle.py from data/; do not edit.\nwindow.LINLOG_DATA = "
    + json.dumps(files, ensure_ascii=False, indent=0)
    + ";\n"
)
(root / "data.js").write_text(out, encoding="utf-8")
print(len(files), "files,", len(out), "bytes")
